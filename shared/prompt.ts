const ADDRESS_LABEL = {
  male: "זכר (אתה, שלך, רוצה)",
  female: "נקבה (את, שלך, רוצה)",
} as const;

/**
 * החלק המשתנה: מי משחק, מה כבר נחשף, ומה התשובה.
 * לשון הפנייה חשובה — בעברית כל פועל בגוף שני מגודר.
 */
export function turnContext(profile: Profile, riddle: Riddle, cluesRevealed: number): string {
  const revealed = riddle.clues.slice(0, cluesRevealed);
  return [
    `שחקן: ${profile.name}, בן/בת ${profile.age}.`,
    `פנה אליו בלשון ${ADDRESS_LABEL[profile.address]}.`,
    "",
    "הרמזים שכבר נחשפו לילד:",
    ...revealed.map((clue, i) => `${i + 1}. ${clue}`),
    revealed.length < riddle.clues.length
      ? `(נשארו ${riddle.clues.length - revealed.length} רמזים שהילד עוד לא ראה — אל תחשוף אותם מילה במילה.)`
      : "(כל הרמזים כבר נחשפו.)",
    "",
    `הפריט הסודי: ${riddle.answer}. הוא נמצא במדף: ${riddle.aisle}.`,
    "לעולם אל תכתוב את המילה הזאת.",
  ].join("\n");
}

/**
 * הודעת פתיחה של עגלי כשנפתחת חידה חדשה.
 * מנוסחת בלי פועל בגוף שני, ולכן מתאימה לשתי לשונות הפנייה.
 */
export function greeting(profile: Profile): string {
  return `היי ${profile.name}! אני עגלי 🛒 אפשר לשאול אותי כל שאלה על הפריט הסודי — חוץ מהתשובה עצמה.`;
}
